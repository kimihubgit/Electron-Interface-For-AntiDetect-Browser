/**
 * Chuyển Base64 sang Uint8Array
 */
function decodeBase64Der(b64) {
  const bin = atob(b64);
  const bytes = new Uint8Array(bin.length);
  for (let i = 0; i < bin.length; i++) {
    bytes[i] = bin.charCodeAt(i);
  }
  return bytes;
}

/**
 * Lắp ráp khóa an toàn trong RAM và import vào WebCrypto
 * Không để lại chuỗi 'BEGIN PUBLIC KEY' nào trong bộ nhớ
 */
export async function getDeobfuscatedCryptoKey() {
  const cryptoSubtle = (typeof window !== 'undefined' ? window.crypto : globalThis.crypto)?.subtle;
  if (!cryptoSubtle) return null;

  try {
    // Giải mã mảng byte DER trực tiếp
    const derBytes = decodeBase64Der(RAW_VAULT_DER_B64);

    const cryptoKey = await cryptoSubtle.importKey(
      'spki',
      derBytes.buffer,
      {
        name: 'RSA-OAEP',
        hash: 'SHA-256'
      },
      false, // Không cho phép extract ngược lại
      ['encrypt']
    );

    // Xoá sạch vùng đệm nhị phân sau khi đã nạp vào Crypto Engine
    derBytes.fill(0);

    return cryptoKey;
  } catch (err) {
    console.error('[KeyVault] Failed to reassemble secure key:', err);
    return null;
  }
}
